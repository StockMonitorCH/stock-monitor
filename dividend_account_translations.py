def T(key: str, **kwargs) -> str:
    try:
        from translations import get_language
        lang = get_language()
    except Exception:
        lang = "DE"
    d = STRINGS.get(lang, STRINGS["DE"])
    text = d.get(key) or STRINGS["DE"].get(key) or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text
